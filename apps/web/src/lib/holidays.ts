const COVERED_YEARS = new Set(Object.keys(TABLE).map((k) => k.slice(0, 4)));

/** 표에 없는 해에 쓰는 날짜 고정 양력 공휴일 (노동절·제헌절은 2026년부터) */
const FIXED: Record<string, string> = {
  '01-01': '신정',
  '03-01': '삼일절',
  '05-01': '노동절',
  '05-05': '어린이날',
  '06-06': '현충일',
  '07-17': '제헌절',
  '08-15': '광복절',
  '10-03': '개천절',
  '10-09': '한글날',
  '12-25': '성탄절',
};

/** 공휴일이면 이름, 아니면 null. ymd = 'YYYY-MM-DD' */
export function holidayName(ymd: string): string | null {
  if (COVERED_YEARS.has(ymd.slice(0, 4))) return TABLE[ymd] ?? null;
  const md = ymd.slice(5);
  if ((md === '05-01' || md === '07-17') && Number(ymd.slice(0, 4)) < 2026) return null;
  return FIXED[md] ?? null;
}

/** 달력 칸처럼 좁은 곳용 짧은 이름 — '대체공휴일(광복절)' → '대체' */
export function holidayShort(name: string): string {
  if (name.startsWith('대체')) return '대체';
  if (name.startsWith('임시')) return '임시';
  if (name.includes(' · ')) return name.split(' · ')[0];
  if (name.endsWith('선거')) return '선거';
  return name.replace(' 연휴', '').replace('부처님 오신 날', '부처님');
}
